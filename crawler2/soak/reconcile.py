"""Pipeline reconciliation: did every unit of work come out the other end, exactly once in effect?

Events observed on the real streams (or generated by the synthetic workload) are recorded
in a SQLite ledger. Each configured *edge* says "every ``from`` event must be followed by a
``to`` event with the same key within ``grace_s``". Per edge the ledger reports:

* ``unaccounted``  - sources older than the grace period with no target (lost or stuck work);
* ``pending``      - sources still inside the grace period;
* ``orphans``      - targets whose source this run never saw (reported, never failed:
  the source may predate the run);
* ``duplicate_effects`` - keys whose targets carry more than one distinct effect (a business
  duplicate), as opposed to ``redeliveries``: the same ``event_id`` observed again
  (at-least-once delivery, explained and counted).

The tailer reads bounded batches per poll (no scans) and reports stream gaps (entries
trimmed before the soak could read them), which make reconciliation INCONCLUSIVE.
"""

from __future__ import annotations

import json
import sqlite3
import subprocess
import time
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol

from crawler2.soak.config import Edge, EvidenceCheck


def extract(obj: Any, path: str) -> list[str]:
    """Values at a dotted path; ``[]`` segments fan out over lists (``payload.refs[].id``)."""
    nodes = [obj]
    for part in path.split("."):
        fan = part.endswith("[]")
        key = part[:-2] if fan else part
        nxt: list[Any] = []
        for node in nodes:
            value = node.get(key) if isinstance(node, dict) else None
            if value is None:
                continue
            nxt.extend(value if fan and isinstance(value, list) else [value])
        nodes = nxt
    return [str(n) for n in nodes if not isinstance(n, dict | list)]


@dataclass
class EdgeResult:
    name: str
    required: bool
    grace_s: float | None
    sources: int = 0
    satisfied: int = 0
    pending: int = 0
    unaccounted: int = 0
    orphans: int = 0
    duplicate_effects: int = 0
    oldest_unaccounted_s: float | None = None
    examples: list[str] = field(default_factory=list)
    """Up to 5 unaccounted keys (ids only) for the operator."""


class Ledger:
    def __init__(self, path: Path, edges: list[Edge]) -> None:
        self._edges = edges
        self._db = sqlite3.connect(path, isolation_level=None)
        self._db.execute("PRAGMA journal_mode=WAL")
        self._db.execute("PRAGMA synchronous=NORMAL")
        self._db.executescript(
            """
            CREATE TABLE IF NOT EXISTS seen(
                event_id TEXT PRIMARY KEY, type TEXT NOT NULL, observed REAL NOT NULL,
                deliveries INTEGER NOT NULL DEFAULT 1);
            CREATE TABLE IF NOT EXISTS edge_events(
                edge TEXT NOT NULL, role TEXT NOT NULL, key TEXT NOT NULL, event_id TEXT NOT NULL,
                ts REAL NOT NULL, observed REAL NOT NULL, effect TEXT,
                PRIMARY KEY(edge, role, event_id, key));
            CREATE TABLE IF NOT EXISTS evidence(id TEXT PRIMARY KEY, ts REAL NOT NULL);
            CREATE INDEX IF NOT EXISTS edge_key ON edge_events(edge, role, key);
            """
        )

    def close(self) -> None:
        self._db.close()

    def ingest(self, envelope: dict[str, Any], observed: float | None = None) -> str:
        """``new``, ``redelivery`` or ``invalid`` (no event id/type)."""
        observed = time.time() if observed is None else observed
        event_id, etype = envelope.get("event_id"), envelope.get("event_type")
        if not isinstance(event_id, str) or not isinstance(etype, str):
            return "invalid"
        cur = self._db.execute(
            "INSERT OR IGNORE INTO seen(event_id, type, observed) VALUES (?,?,?)",
            (event_id, etype, observed),
        )
        if cur.rowcount == 0:
            self._db.execute(
                "UPDATE seen SET deliveries = deliveries + 1 WHERE event_id = ?", (event_id,)
            )
            return "redelivery"
        ts = _ts(envelope.get("occurred_at"), observed)
        if etype == "evidence.finalized":
            for eid in extract(envelope, "payload.seal.evidence_id"):
                self._db.execute("INSERT OR IGNORE INTO evidence VALUES (?,?)", (eid, ts))
        rows: list[tuple[Any, ...]] = []
        for edge in self._edges:
            if etype == edge.from_type:
                rows += [
                    (edge.name, "from", k, event_id, ts, observed, None)
                    for k in extract(envelope, edge.from_key)
                ]
            if etype in edge.to_types and _passes(envelope, edge.to_filters.get(etype)):
                effects = extract(envelope, edge.effect_path) if edge.effect_path else []
                effect = effects[0] if effects else None
                path = edge.to_key_by_type.get(etype, edge.to_key)
                rows += [
                    (edge.name, "to", k, event_id, ts, observed, effect)
                    for k in extract(envelope, path)
                ]
        self._db.executemany("INSERT OR IGNORE INTO edge_events VALUES (?,?,?,?,?,?,?)", rows)
        return "new"

    def finalized_evidence(self, limit: int = 1000) -> list[str]:
        return [
            r[0]
            for r in self._db.execute("SELECT id FROM evidence ORDER BY ts DESC LIMIT ?", (limit,))
        ]

    def stage_counts(self) -> dict[str, int]:
        return dict(self._db.execute("SELECT type, COUNT(*) FROM seen GROUP BY type"))

    def redeliveries(self) -> dict[str, int]:
        return dict(
            self._db.execute(
                "SELECT type, SUM(deliveries - 1) FROM seen GROUP BY type HAVING SUM(deliveries - 1) > 0"
            )
        )

    def edge_results(self, now: float, run_started: float) -> list[EdgeResult]:
        out: list[EdgeResult] = []
        q = self._db.execute
        for edge in self._edges:
            res = EdgeResult(edge.name, edge.required, edge.grace_s)
            res.sources = q(
                "SELECT COUNT(DISTINCT key) FROM edge_events WHERE edge=? AND role='from'",
                (edge.name,),
            ).fetchone()[0]
            res.satisfied = q(
                """SELECT COUNT(DISTINCT f.key) FROM edge_events f WHERE f.edge=? AND f.role='from'
                   AND EXISTS(SELECT 1 FROM edge_events t WHERE t.edge=f.edge AND t.role='to' AND t.key=f.key)""",
                (edge.name,),
            ).fetchone()[0]
            open_rows = q(
                """SELECT f.key, MIN(f.observed) FROM edge_events f WHERE f.edge=? AND f.role='from'
                   AND NOT EXISTS(SELECT 1 FROM edge_events t WHERE t.edge=f.edge AND t.role='to' AND t.key=f.key)
                   GROUP BY f.key ORDER BY MIN(f.observed)""",
                (edge.name,),
            ).fetchall()
            for key, first_seen in open_rows:
                if edge.grace_s is not None and now - first_seen > edge.grace_s:
                    res.unaccounted += 1
                    if len(res.examples) < 5:
                        res.examples.append(str(key))
                    age = now - first_seen
                    res.oldest_unaccounted_s = max(res.oldest_unaccounted_s or 0.0, age)
                else:
                    res.pending += 1
            res.orphans = q(
                """SELECT COUNT(DISTINCT t.key) FROM edge_events t WHERE t.edge=? AND t.role='to' AND t.ts>=?
                   AND NOT EXISTS(SELECT 1 FROM edge_events f WHERE f.edge=t.edge AND f.role='from' AND f.key=t.key)""",
                (edge.name, run_started),
            ).fetchone()[0]
            res.duplicate_effects = q(
                """SELECT COUNT(*) FROM (SELECT key FROM edge_events WHERE edge=? AND role='to'
                   AND effect IS NOT NULL GROUP BY key HAVING COUNT(DISTINCT effect) > 1)""",
                (edge.name,),
            ).fetchone()[0]
            out.append(res)
        return out


def _passes(envelope: dict[str, Any], conditions: dict[str, str] | None) -> bool:
    return all(extract(envelope, path) == [want] for path, want in (conditions or {}).items())


def _ts(value: Any, fallback: float) -> float:
    from datetime import datetime

    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00")).timestamp()
    except ValueError:
        return fallback


# --- stream tailing ---------------------------------------------------------------------


@dataclass
class TailResult:
    ingested: int = 0
    redeliveries: int = 0
    invalid: int = 0
    gaps: list[dict[str, Any]] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)


class StreamTailer:
    """Reads new entries of the configured event streams into the ledger, a bounded batch per call."""

    def __init__(
        self, client: Any, streams: dict[str, str], ledger: Ledger, *, batch: int = 500
    ) -> None:
        self._client = client
        self._streams = streams  # event_type -> stream key
        self._ledger = ledger
        self._batch = batch

    def _info(self, key: str) -> dict[str, Any] | None:
        """XINFO STREAM, or None while the stream does not exist yet (no event was ever published)."""
        try:
            info: dict[str, Any] = self._client.xinfo_stream(key)
        except Exception as exc:
            if "no such key" in str(exc).lower():
                return None
            raise
        return info

    def start_positions(self) -> dict[str, dict[str, Any]]:
        """Begin at the current end of every stream: only events during the soak are judged."""
        pos: dict[str, dict[str, Any]] = {}
        for etype, key in self._streams.items():
            info = self._info(key)  # a transport error here fails the start, loudly
            if info is None:
                pos[etype] = {"id": "0-0", "added": 0}
            else:
                pos[etype] = {"id": info["last-generated-id"], "added": info.get("entries-added")}
        return pos

    def poll(self, positions: dict[str, dict[str, Any]]) -> TailResult:
        result = TailResult()
        for etype, key in self._streams.items():
            state = positions.setdefault(etype, {"id": "0-0", "added": 0})
            got = 0
            try:
                while True:
                    entries = self._client.xrange(key, min=f"({state['id']}", count=self._batch)
                    if not entries:
                        break
                    for entry_id, fields in entries:
                        got += 1
                        state["id"] = entry_id
                        raw = fields.get("envelope")
                        try:
                            verdict = self._ledger.ingest(json.loads(raw))
                        except (TypeError, ValueError):
                            verdict = "invalid"
                        if verdict == "redelivery":
                            result.redeliveries += 1
                        elif verdict == "invalid":
                            result.invalid += 1
                        else:
                            result.ingested += 1
                    if len(entries) < self._batch:
                        break
                info = self._info(key)
                added = info.get("entries-added") if info else None
                if added is not None and state.get("added") is not None:
                    missed = (added - state["added"]) - got
                    if missed > 0:
                        result.gaps.append(
                            {"stream": key, "event_type": etype, "entries_lost": missed}
                        )
                if added is not None:
                    state["added"] = added
            except Exception as exc:  # noqa: BLE001
                result.errors.append(f"{etype}: {str(exc)[:100]}")
        return result


# --- evidence integrity ------------------------------------------------------------------


@dataclass
class EvidenceResult:
    checked: int = 0
    mismatched: list[str] = field(default_factory=list)
    missing: list[str] = field(default_factory=list)
    unverifiable: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)


class EvidenceVerifier(Protocol):
    def verify(self, evidence_ids: list[str]) -> EvidenceResult: ...


class CommandEvidenceVerifier:
    """Re-validates evidence with the project's own validator (read-only: ``--dry-run``)."""

    def __init__(self, cfg: EvidenceCheck) -> None:
        self._cfg = cfg

    def verify(self, evidence_ids: list[str]) -> EvidenceResult:
        res = EvidenceResult()
        for eid in evidence_ids[: self._cfg.sample]:
            argv = [a.replace("{id}", eid) for a in self._cfg.command]
            try:
                done = subprocess.run(
                    argv, capture_output=True, text=True, timeout=self._cfg.timeout_s, check=False
                )
                doc = json.loads(done.stdout)
            except (subprocess.SubprocessError, OSError, ValueError) as exc:
                res.errors.append(f"{eid}: {str(exc)[:80]}")
                continue
            res.checked += 1
            artifacts = doc.get("artifacts", {})
            if doc.get("outcome") == "rejected" or artifacts.get("corrupted", 0):
                res.mismatched.append(eid)
            if artifacts.get("missing", 0):
                res.missing.append(eid)
            if artifacts.get("unverifiable", 0) or artifacts.get("oversized", 0):
                res.unverifiable.append(eid)
            if "error" in doc:
                res.errors.append(f"{eid}: {doc['error'][:80]}")
        return res


def iter_chunks(items: list[str], n: int) -> Iterator[list[str]]:
    for i in range(0, len(items), n):
        yield items[i : i + n]
